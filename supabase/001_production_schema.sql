-- ---------- Helpers ----------
create or replace function public.normalize_phone(value text)
returns text
language sql
immutable
as $$
  select regexp_replace(coalesce(value, ''), '[^0-9]', '', 'g');
$$;

create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  email text,
  created_at timestamptz not null default now()
);

alter table public.admin_users enable row level security;

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users a where a.user_id = auth.uid()
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to authenticated;

-- ---------- Catalog ----------
create table if not exists public.products (
  id bigint generated by default as identity primary key,
  sku text unique,
  name text not null check (char_length(name) between 2 and 160),
  category text not null check (category in ('camisole','outer','bottoms','accessories')),
  product_type text not null check (product_type in ('top','bottom','acc')),
  price numeric(12,2) not null check (price >= 0),
  image_url text not null,
  description text not null default '',
  colors text[] not null default '{}'::text[],
  stock integer not null default 0 check (stock >= 0),
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.coupons (
  code text primary key,
  percent_off numeric(5,2) not null check (percent_off > 0 and percent_off <= 100),
  active boolean not null default true,
  starts_at timestamptz,
  ends_at timestamptz,
  created_at timestamptz not null default now()
);

insert into public.coupons(code, percent_off, active)
values ('FAIRY10', 10, true)
on conflict (code) do update set percent_off = excluded.percent_off, active = excluded.active;

-- ---------- Customers / orders ----------
create table if not exists public.customers (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  phone text not null unique,
  email text,
  address text,
  subdistrict text,
  district text,
  province text,
  zipcode text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.orders (
  id uuid primary key default gen_random_uuid(),
  order_no text not null unique,
  customer_id uuid references public.customers(id) on delete set null,
  customer_name text,
  phone text,
  email text,
  address text,
  subdistrict text,
  district text,
  province text,
  zipcode text,
  subtotal numeric(12,2) not null default 0 check (subtotal >= 0),
  discount numeric(12,2) not null default 0 check (discount >= 0),
  total numeric(12,2) not null default 0 check (total >= 0),
  coupon_code text,
  payment_method text not null check (payment_method in ('card','promptpay','cod')),
  payment_status text not null default 'pending' check (payment_status in ('pending','unpaid','paid','failed','refunded')),
  status text not null default 'pending' check (status in ('awaiting_payment','pending','packing','shipped','completed','cancelled')),
  tracking_no text,
  stripe_session_id text unique,
  stock_released_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id uuid not null references public.orders(id) on delete cascade,
  product_id bigint references public.products(id) on delete set null,
  product_name text not null,
  unit_price numeric(12,2) not null check (unit_price >= 0),
  quantity integer not null check (quantity between 1 and 10),
  size text not null default 'Freesize',
  created_at timestamptz not null default now()
);

create index if not exists idx_orders_created_at on public.orders(created_at desc);
create index if not exists idx_orders_phone on public.orders(phone);
create index if not exists idx_orders_status on public.orders(status);
create index if not exists idx_order_items_order_id on public.order_items(order_id);
create index if not exists idx_products_active on public.products(active);


-- ---------- Server-side order creation ----------
create or replace function public.create_order(
  p_name text,
  p_phone text,
  p_email text,
  p_address text,
  p_subdistrict text,
  p_district text,
  p_province text,
  p_zipcode text,
  p_payment_method text,
  p_coupon_code text,
  p_items jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_phone text := public.normalize_phone(p_phone);
  v_customer_id uuid;
  v_order_id uuid;
  v_order_no text;
  v_subtotal numeric(12,2) := 0;
  v_discount numeric(12,2) := 0;
  v_total numeric(12,2) := 0;
  v_percent numeric(5,2) := 0;
  v_item jsonb;
  v_product public.products%rowtype;
  v_qty integer;
  v_size text;
  v_resolved_items jsonb := '[]'::jsonb;
begin
  if coalesce(char_length(trim(p_name)),0) < 2 then raise exception 'กรุณากรอกชื่อผู้รับ'; end if;
  if char_length(v_phone) < 9 or char_length(v_phone) > 10 then raise exception 'เบอร์โทรศัพท์ไม่ถูกต้อง'; end if;
  if (select count(*) from public.orders where phone = v_phone and created_at > now() - interval '15 minutes' and status in ('awaiting_payment','pending','packing')) >= 3 then raise exception 'มีคำสั่งซื้อที่กำลังดำเนินการจากเบอร์นี้หลายรายการ กรุณารอสักครู่หรือติดต่อร้าน'; end if;
  if coalesce(char_length(trim(p_address)),0) < 3 or coalesce(char_length(trim(p_province)),0) < 2 then raise exception 'กรุณากรอกที่อยู่จัดส่งให้ครบ'; end if;
  if p_payment_method not in ('card','promptpay','cod') then raise exception 'วิธีชำระเงินไม่ถูกต้อง'; end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) = 0 or jsonb_array_length(p_items) > 20 then raise exception 'ตะกร้าสินค้าไม่ถูกต้อง'; end if;

  for v_item in select * from jsonb_array_elements(p_items)
  loop
    v_qty := coalesce((v_item->>'quantity')::integer, 0);
    if v_qty < 1 or v_qty > 10 then raise exception 'จำนวนสินค้าต่อรายการต้องอยู่ระหว่าง 1-10 ชิ้น'; end if;

    select * into v_product
    from public.products
    where id = (v_item->>'product_id')::bigint
    for update;

    if not found or v_product.active is not true then raise exception 'มีสินค้าที่ไม่พร้อมจำหน่าย'; end if;
    if v_product.stock < v_qty then raise exception 'สินค้า % มีสต็อกไม่เพียงพอ', v_product.name; end if;

    v_size := left(coalesce(nullif(trim(v_item->>'size'),''),'Freesize'), 30);
    v_subtotal := v_subtotal + (v_product.price * v_qty);
    v_resolved_items := v_resolved_items || jsonb_build_array(jsonb_build_object(
      'product_id', v_product.id,
      'name', v_product.name,
      'unit_price', v_product.price,
      'quantity', v_qty,
      'size', v_size
    ));

    -- Reserve stock inside the same database transaction. If anything later fails, PostgreSQL rolls this back.
    update public.products set stock = stock - v_qty where id = v_product.id;
  end loop;

  if nullif(trim(coalesce(p_coupon_code,'')),'') is not null then
    select percent_off into v_percent
    from public.coupons
    where upper(code) = upper(trim(p_coupon_code))
      and active = true
      and (starts_at is null or starts_at <= now())
      and (ends_at is null or ends_at >= now());
    if not found then raise exception 'โค้ดส่วนลดไม่ถูกต้องหรือหมดอายุ'; end if;
    v_discount := round(v_subtotal * (v_percent / 100.0), 2);
  end if;

  v_total := greatest(0, v_subtotal - v_discount);
  if v_total < 10 and p_payment_method in ('card','promptpay') then raise exception 'ยอดชำระออนไลน์ขั้นต่ำ 10 บาท'; end if;

  insert into public.customers(name, phone, email, address, subdistrict, district, province, zipcode)
  values(trim(p_name), v_phone, nullif(trim(coalesce(p_email,'')),''), trim(p_address), trim(p_subdistrict), trim(p_district), trim(p_province), trim(p_zipcode))
  on conflict (phone) do update set
    name = excluded.name,
    email = coalesce(excluded.email, public.customers.email),
    address = excluded.address,
    subdistrict = excluded.subdistrict,
    district = excluded.district,
    province = excluded.province,
    zipcode = excluded.zipcode,
    updated_at = now()
  returning id into v_customer_id;

  v_order_no := 'FM-' || to_char(clock_timestamp(), 'YYYYMMDDHH24MISS') || '-' || upper(substr(replace(gen_random_uuid()::text,'-',''),1,6));

  insert into public.orders(
    order_no, customer_id, customer_name, phone, email, address, subdistrict, district, province, zipcode,
    subtotal, discount, total, coupon_code, payment_method, payment_status, status
  ) values (
    v_order_no, v_customer_id, trim(p_name), v_phone, nullif(trim(coalesce(p_email,'')),''), trim(p_address), trim(p_subdistrict), trim(p_district), trim(p_province), trim(p_zipcode),
    v_subtotal, v_discount, v_total, nullif(upper(trim(coalesce(p_coupon_code,''))),''), p_payment_method,
    case when p_payment_method = 'cod' then 'unpaid' else 'pending' end,
    case when p_payment_method = 'cod' then 'pending' else 'awaiting_payment' end
  ) returning id into v_order_id;

  for v_item in select * from jsonb_array_elements(v_resolved_items)
  loop
    insert into public.order_items(order_id, product_id, product_name, unit_price, quantity, size)
    values(v_order_id, (v_item->>'product_id')::bigint, v_item->>'name', (v_item->>'unit_price')::numeric, (v_item->>'quantity')::integer, v_item->>'size');

  end loop;

  return jsonb_build_object(
    'order_id', v_order_id,
    'order_no', v_order_no,
    'subtotal', v_subtotal,
    'discount', v_discount,
    'total', v_total,
    'payment_method', p_payment_method,
    'items', v_resolved_items
  );
end;
$$;

revoke all on function public.create_order(text,text,text,text,text,text,text,text,text,text,jsonb) from public, anon, authenticated;
grant execute on function public.create_order(text,text,text,text,text,text,text,text,text,text,jsonb) to service_role;

-- Release reserved inventory once (for expired/failed/cancelled online payments).
create or replace function public.release_order_stock(p_order_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_item record;
  v_released timestamptz;
  v_payment_status text;
begin
  select stock_released_at, payment_status into v_released, v_payment_status from public.orders where id = p_order_id for update;
  if not found or v_released is not null or v_payment_status = 'paid' then return; end if;

  for v_item in select product_id, quantity from public.order_items where order_id = p_order_id and product_id is not null
  loop
    update public.products set stock = stock + v_item.quantity where id = v_item.product_id;
  end loop;

  update public.orders set stock_released_at = now(), updated_at = now() where id = p_order_id;
end;
$$;

revoke all on function public.release_order_stock(uuid) from public, anon, authenticated;
grant execute on function public.release_order_stock(uuid) to service_role;

-- Public order tracking requires BOTH order number and phone number.
create or replace function public.track_order(p_order_no text, p_phone text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  v_order public.orders%rowtype;
  v_items jsonb;
begin
  select * into v_order
  from public.orders
  where upper(order_no) = upper(trim(p_order_no))
    and phone = public.normalize_phone(p_phone)
  limit 1;

  if not found then return null; end if;

  select coalesce(jsonb_agg(jsonb_build_object(
    'name', product_name,
    'quantity', quantity,
    'size', size,
    'unit_price', unit_price
  ) order by id), '[]'::jsonb)
  into v_items
  from public.order_items where order_id = v_order.id;

  return jsonb_build_object(
    'order_no', v_order.order_no,
    'customer_name', v_order.customer_name,
    'total', v_order.total,
    'payment_method', v_order.payment_method,
    'payment_status', v_order.payment_status,
    'status', v_order.status,
    'tracking_no', coalesce(v_order.tracking_no, '-'),
    'created_at', v_order.created_at,
    'items', v_items
  );
end;
$$;

revoke all on function public.track_order(text,text) from public, anon, authenticated;
grant execute on function public.track_order(text,text) to service_role;

-- Admin order update: restores stock automatically when an order is cancelled.
create or replace function public.admin_update_order(
  p_order_id uuid,
  p_status text,
  p_tracking_no text,
  p_payment_status text
)
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  v_current_status text;
  v_item record;
  v_released timestamptz;
begin
  if not public.is_admin() then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  if p_status not in ('awaiting_payment','pending','packing','shipped','completed','cancelled') then raise exception 'สถานะออเดอร์ไม่ถูกต้อง'; end if;
  if p_payment_status not in ('pending','unpaid','paid','failed','refunded') then raise exception 'สถานะการชำระเงินไม่ถูกต้อง'; end if;

  select status, stock_released_at into v_current_status, v_released from public.orders where id = p_order_id for update;
  if not found then raise exception 'ไม่พบออเดอร์'; end if;
  if v_current_status = 'awaiting_payment' and p_status = 'cancelled' then raise exception 'ออเดอร์นี้กำลังอยู่ใน Stripe Checkout กรุณารอให้ Session หมดอายุหรือจัดการจาก Stripe ก่อน'; end if;

  if p_status = 'cancelled' and v_current_status <> 'cancelled' and v_released is null then
    for v_item in select product_id, quantity from public.order_items where order_id = p_order_id and product_id is not null
    loop
      update public.products set stock = stock + v_item.quantity where id = v_item.product_id;
    end loop;
    update public.orders set stock_released_at = now() where id = p_order_id;
  end if;

  update public.orders set
    status = p_status,
    tracking_no = nullif(trim(coalesce(p_tracking_no,'')),''),
    payment_status = p_payment_status,
    updated_at = now()
  where id = p_order_id;
end;
$$;

revoke all on function public.admin_update_order(uuid,text,text,text) from public, anon;
grant execute on function public.admin_update_order(uuid,text,text,text) to authenticated;

-- Delete personal customer data while preserving anonymized accounting/order history.
create or replace function public.delete_customer_personal_data(p_customer_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.is_admin() then raise exception 'ไม่มีสิทธิ์ใช้งาน'; end if;
  if exists (
    select 1 from public.orders
    where customer_id = p_customer_id
      and status not in ('completed','cancelled')
  ) then
    raise exception 'ยังมีออเดอร์ที่กำลังดำเนินการ กรุณาปิดออเดอร์ให้เสร็จก่อนลบข้อมูลส่วนตัว';
  end if;

  update public.orders set
    customer_name = 'ลูกค้าที่ลบข้อมูลแล้ว',
    phone = null,
    email = null,
    address = null,
    subdistrict = null,
    district = null,
    province = null,
    zipcode = null,
    updated_at = now()
  where customer_id = p_customer_id;

  delete from public.customers where id = p_customer_id;
